#!/usr/bin/env python3
"""Generate the two Essentia files abcd's native build needs, so the build itself needs no Python.

Essentia's own build (waf) generates `essentia_algorithms_reg.cpp` (which registers every compiled
algorithm with the AlgorithmFactory) and `version.h`. We compile only the algorithms abcd uses plus
the ones those create at run time, so this script:

  1. starts from ROOT_ALGORITHMS,
  2. follows every `AlgorithmFactory::create("Name")` found in the sources, and
  3. writes the registry for exactly that set, and the list of source files to compile.

Run from anywhere after `git submodule update --init`; commit the outputs:

    python dj-native/scripts/generate_essentia_registry.py

Outputs (in dj-native/src/main/cpp/essentia_generated/):
    essentia_algorithms_reg.cpp   registry for the selected algorithms
    version.h                     Essentia version header
    algorithms.cmake              list of algorithm source files, included by CMakeLists.txt

Essentia is AGPL-3.0 (see NOTICE.md).
"""

import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MODULE = os.path.dirname(HERE)  # dj-native/
ESSENTIA = os.path.join(MODULE, "third_party", "essentia")
OUT_DIR = os.path.join(MODULE, "src", "main", "cpp", "essentia_generated")

# What abcd's analyzer uses directly or reaches through the factory.
ROOT_ALGORITHMS = [
    "RhythmExtractor2013",  # BPM, beat ticks, confidence
    "KeyExtractor",  # key, scale, strength
    "Windowing",  # analysis frames for the structure features
    "Spectrum",
    "SpectralPeaks",
    "HPCP",  # chroma per frame
    "MFCC",  # timbre per frame
    "FFT",  # resolved to FFTK (KissFFT) below
]

FFT_ALIASES = {"FFT": "FFTK", "IFFT": "IFFTK"}  # KissFFT build: no FFTW, no Accelerate.

# Algorithms that need libraries abcd does not link (FFmpeg, taglib, yaml, samplerate, FFTW, ...).
UNAVAILABLE = {
    "FFTW", "IFFTW", "FFTA", "IFFTA", "AudioLoader", "MonoLoader", "EasyLoader", "EqloudLoader",
    "AudioWriter", "MonoWriter", "MetadataReader", "YamlInput", "YamlOutput", "Resample",
    "Chromaprinter", "AudioOnsetsMarker", "LPC",
}

CREATE_RE = re.compile(r'create\(\s*"(\w+)"')


def main():
    if not os.path.isdir(os.path.join(ESSENTIA, "src")):
        sys.exit("Essentia submodule missing. Run: git submodule update --init dj-native/third_party/essentia")
    sys.path.insert(0, ESSENTIA)
    from utils.algorithms_info import create_registration_cpp, create_version_h, get_all_algorithms

    src_dir = os.path.join(ESSENTIA, "src")
    all_algos = get_all_algorithms(os.path.join(src_dir, "algorithms"), root_dir=src_dir)

    selected = {}
    queue = [FFT_ALIASES.get(name, name) for name in ROOT_ALGORITHMS]
    while queue:
        name = queue.pop()
        name = FFT_ALIASES.get(name, name)
        if name in selected or name in UNAVAILABLE:
            continue
        if name not in all_algos:
            sys.exit("Algorithm not found in Essentia: %s" % name)
        selected[name] = all_algos[name]
        source = os.path.join(src_dir, all_algos[name]["source"])
        for path in (source, source[:-4] + ".h"):
            if os.path.isfile(path):
                with open(path, encoding="utf8", errors="replace") as handle:
                    queue.extend(CREATE_RE.findall(handle.read()))

    os.makedirs(OUT_DIR, exist_ok=True)
    version = open(os.path.join(ESSENTIA, "VERSION")).read().strip()
    sha = subprocess.run(
        ["git", "-C", ESSENTIA, "rev-parse", "--short", "HEAD"], capture_output=True, text=True
    ).stdout.strip() or "unknown"

    # Both generators write to a path relative to the Essentia root, so run from there.
    os.chdir(ESSENTIA)
    reg_path = os.path.join(OUT_DIR, "essentia_algorithms_reg.cpp")
    create_registration_cpp(selected, reg_path, use_streaming=True)
    create_version_h(os.path.join(OUT_DIR, "version.h"), version, sha)

    sources = sorted(selected[name]["source"].replace("\\", "/") for name in selected)
    with open(os.path.join(OUT_DIR, "algorithms.cmake"), "w", newline="\n") as out:
        out.write("# Generated by dj-native/scripts/generate_essentia_registry.py. Do not edit.\n")
        out.write("# Essentia %s (%s). Paths are relative to third_party/essentia/src.\n" % (version, sha))
        out.write("set(ESSENTIA_ALGORITHM_SOURCES\n")
        for source in sources:
            out.write("    %s\n" % source)
        out.write(")\n")
    print("Selected %d algorithms: %s" % (len(selected), ", ".join(sorted(selected))))


if __name__ == "__main__":
    main()
